"""state.json — служебная память бота.

Хранит пять вещей: offset телеграма (чтобы после перезапуска не разбирать всё
заново), уже разобранные файлы, последний прочитанный справочник статей,
очередь строк, не доехавших до таблицы, и последнюю записанную строку по
каждому каналу — из неё потом делается правка.

Удалять можно, только когда очередь пуста: если бот отвечал «Разобрал, но
в таблицу не попало — попробую позже», в файле лежат строки расходов, которых
больше нигде нет. Белого списка здесь намеренно нет, он живёт в settings.json.
"""

import json
import threading
import time
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
STATE_PATH = BASE_DIR / "state.json"

EMPTY = {
    "offset": 0,
    "seen": {},
    "last": {},
    "categories": [],
    "categories_at": 0,
    "queue": [],
}

# Разобранные файлы не должны копиться бесконечно: они нужны, чтобы поймать
# чек, присланный дважды подряд, а не чтобы помнить всё за год.
SEEN_LIMIT = 500

# Пишут в файл два потока — телеграмный и поток разбора. Без замка они
# затрут запись друг друга на середине.
_LOCK = threading.Lock()


def load():
    """Память бота. Файла нет или он испорчен — начинаем с чистой заготовки."""
    state = json.loads(json.dumps(EMPTY))
    try:
        data = json.loads(STATE_PATH.read_text(encoding="utf-8"))
        state.update(data)
    except (FileNotFoundError, json.JSONDecodeError, TypeError, ValueError):
        return json.loads(json.dumps(EMPTY))
    if not isinstance(state["seen"], dict):
        # Файл от прежней версии бота: там был список отпечатков без номеров
        # строк. Разбирать его незачем — потеря невелика, а формат чистый.
        state["seen"] = {}
    return state


def save(state):
    """Пишем через временный файл: Ctrl+C посреди записи не оставит огрызок,
    из которого бот потом не поднимется."""
    with _LOCK:
        tmp = STATE_PATH.with_name("state.json.tmp")
        tmp.write_text(json.dumps(state, ensure_ascii=False, indent=2),
                       encoding="utf-8")
        tmp.replace(STATE_PATH)


def seen(state, mark):
    """Этот файл уже разбирали? Отдаёт запомненное — номер строки и время —
    или None. Отпечаток у телеграма file_unique_id, у браузера хеш файла."""
    return state["seen"].get(mark)


def remember(state, mark, row, file=""):
    """Запомнить разобранный файл. row может быть None: строка ушла в очередь
    и номера у неё пока нет — но разбирать этот чек второй раз всё равно не надо.

    Имя файла помнится ради превью: повтор бот опознаёт до записи на диск,
    второй копии не появляется, и показать в ленте он может только ту, первую.
    Без имени пузырь повтора откатывался к «02-мятый.jpg», хотя сама
    фотография лежит в папке «чеки» и никуда не делась."""
    state["seen"][mark] = {"row": row, "at": time.time(), "file": file}
    extra = len(state["seen"]) - SEEN_LIMIT
    if extra > 0:
        for old in list(state["seen"])[:extra]:
            del state["seen"][old]


def address(channel, author):
    """Адрес памяти: чья это последняя строка.

    У браузера адрес один на всех: рабочее место открыто на одном компьютере,
    и человек за ним один, как бы он ни назвал себя в настройках. У телеграма
    свой адрес на каждого — там людей несколько, и последняя строка у каждого
    своя.

    Префикс латиницей и с двоеточием, а не просто имя: имя человека приходит
    из телеграма и может оказаться любым, вплоть до слова «web». Разбирать
    адрес обратно мы никогда не будем — его только сравнивают целиком."""
    if channel == "браузер":
        return "web"
    return "tg:" + author


def last(state, address):
    """Последняя строка, записанная по этому адресу, или None."""
    return state["last"].get(address)


def remember_last(state, address, record):
    """Запомнить последнюю записанную строку.

    Хранится строка целиком, все десять полей: правка сравнивает старую запись
    с новой, и сравнивать надо со всеми полями сразу, а не с суммой и
    продавцом. Время ставит сама функция, а не тот, кто её позвал: по этому
    времени потом решается, кто написал последним, и подделывать его не должно
    быть возможности даже по невнимательности.

    Растёт эта память ровно на одну запись в человека из белого списка —
    ограничивать её, как seen, незачем."""
    state["last"][address] = dict(record, at=time.time())


def newest(state):
    """Самая свежая запись из всех адресов — и адрес, по которому она лежит.

    Нужна, чтобы не поправить чужое. «Не 450, а 480» в браузере относится к
    тому, что человек видит внизу ленты, а внизу ленты стоит последняя запись
    любого канала — своя или Марии из телеграма."""
    spot, fresh = None, None
    for key, record in state["last"].items():
        if fresh is None or record["at"] > fresh["at"]:
            spot, fresh = key, record
    return spot, fresh
