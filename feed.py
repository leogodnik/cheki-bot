"""Лента рабочего места — журнал событий в памяти процесса.

В state.json ленты нет: её сохранение — работа следующего среза, не этого.
Перезапустили бота — лента пуста, а записи никуда не делись: они в таблице,
за тем таблица и нужна.

Пишут сюда из двух потоков — телеграмного и веб-запросов, — поэтому номер
события выдаётся под замком. Без него два события получили бы один номер, и
страница одно из них не показала бы.
"""

import threading
import time
from uuid import uuid4

# Лента не растёт бесконечно: она нужна, чтобы видеть сегодняшнюю работу,
# а не чтобы помнить всё за год.
LIMIT = 300

# Метка жизни процесса — рождается раз при импорте модуля и живёт, пока жив
# бот. Опрос возит её в запросе, оба маршрута — в ответе: своя метка не
# совпала с нашей — значит, бот перезапустили, и since() ниже отдаёт журнал
# целиком, а не то, что просили по номеру.
LIFE = uuid4().hex[:8]

_LOCK = threading.Lock()
_EVENTS = []
_NEXT = 1


def add(event):
    """Кладёт событие в ленту и возвращает его же — уже с номером и временем.

    Номер нужен странице: по нему она спрашивает «что нового после N-го»."""
    global _NEXT
    with _LOCK:
        stamped = dict(event, id=_NEXT, at=time.time())
        _NEXT += 1
        _EVENTS.append(stamped)
        del _EVENTS[:-LIMIT]
        return stamped


def since(after, life=""):
    """Всё, что появилось после события с номером after.

    Возвращает (события, номер последнего). Если after больше последнего
    номера или пришедшая метка life не совпадает с LIFE — оба раза это
    значит одно и то же: страница помнит номера из другой жизни бота, и её
    after ничего не значит. Отдаём журнал целиком, будто спросили с нуля.
    Пустая метка (старые вызовы, самопроверка) в сравнении не участвует —
    тогда решает только число."""
    with _LOCK:
        newest = _EVENTS[-1]["id"] if _EVENTS else 0
        if after > newest or (life and life != LIFE):
            after = 0
        fresh = [event for event in _EVENTS if event["id"] > after]
        return fresh, newest


def forget():
    """Забыть всё. Нужно только самопроверке — бот этого не делает."""
    global _NEXT
    with _LOCK:
        _EVENTS.clear()
        _NEXT = 1
