"""Лента рабочего места — журнал событий в памяти процесса.

В state.json ленты нет: её сохранение — работа следующего среза, не этого.
Перезапустили бота — лента пуста, а записи никуда не делись: они в таблице,
за тем таблица и нужна.

Пишут сюда из двух потоков — телеграмного и веб-запросов, — поэтому номер
события выдаётся под замком. Без него два события получили бы один номер, и
страница одно из них не показала бы.
"""

import threading
import time
from uuid import uuid4

# Лента не растёт бесконечно: она нужна, чтобы видеть сегодняшнюю работу,
# а не чтобы помнить всё за год.
LIMIT = 300

# Метка жизни процесса — рождается раз при импорте модуля и живёт, пока жив
# бот. Страница возит её в каждом запросе и ответе: своя метка не совпала с
# нашей — значит, бот перезапустили, и since() ниже отдаёт журнал целиком,
# а не то, что просили по номеру.
LIFE = uuid4().hex[:8]

_LOCK = threading.Lock()
_EVENTS = []
_NEXT = 1


def add(event):
    """Кладёт событие в ленту и возвращает его же — уже с номером и временем.

    Номер нужен странице: по нему она спрашивает «что нового после N-го»."""
    global _NEXT
    with _LOCK:
        stamped = dict(event, id=_NEXT, at=time.time())
        _NEXT += 1
        _EVENTS.append(stamped)
        del _EVENTS[:-LIMIT]
        return stamped


def since(after, life=""):
    """Всё, что появилось после события с номером after.

    Возвращает (события, номер последнего). Два признака одного и того же:
    собеседник помнит не эту жизнь бота, и его after ничего не значит, даже
    если по числу похож на правду. Первый — after больше последнего номера,
    такое бывает сразу после перезапуска, пока новых событий ещё меньше,
    чем окно старой жизни. Второй — пришедшая метка life не совпадает с
    LIFE: числа при этом могут случайно совпасть (например, обе жизни
    отдали только два события), а вот метка не совпадёт никогда. В обоих
    случаях отдаём журнал целиком, будто спросили с нуля. Пустая метка
    (старые вызовы, самопроверка) в сравнении не участвует — тогда решает
    только число."""
    with _LOCK:
        newest = _EVENTS[-1]["id"] if _EVENTS else 0
        if after > newest or (life and life != LIFE):
            after = 0
        fresh = [event for event in _EVENTS if event["id"] > after]
        return fresh, newest


def forget():
    """Забыть всё. Нужно только самопроверке — бот этого не делает."""
    global _NEXT
    with _LOCK:
        _EVENTS.clear()
        _NEXT = 1
