"""Мастер установки: то, что можно проверить без Flask и без интернета.

Три чистые функции. Первая собирает код для Apps Script с подставленным
секретом. Вторая узнаёт, что за адрес вставил человек. Третья говорит, что
не так со справочником статей.

Две последние существуют потому, что обе ошибки установки, случившиеся при
первой живой настройке, — это ошибки человека, а не программы. Программа
работала правильно оба раза; правильным ответом было бы объяснить.
"""

import secrets
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
SCRIPT_PATH = BASE_DIR / "sheet.gs"

# Ровно один раз встречается в sheet.gs, в первой строке, внутри кавычек.
PLACEHOLDER = "__СЕКРЕТ__"


def new_secret():
    """Секрет придумывает машина.

    Придуманный человеком будет либо «12345», либо забыт при вставке во второе
    место. Алфавит token_urlsafe — буквы, цифры, дефис и подчёркивание:
    экранировать в JavaScript нечего, кавычки в коде трогать не нужно."""
    return secrets.token_urlsafe(16)


def script_with_secret(secret):
    """sheet.gs с подставленным секретом — тот текст, который человек скопирует
    в редактор Apps Script.

    Заглушки в файле не нашлось — отказываемся, и это не перестраховка.
    Показать ученику код с __СЕКРЕТ__ внутри значит опубликовать скрипт,
    который пускает любого, кто пришлёт слово __СЕКРЕТ__. Требование
    sheet-setup.md, раздел «Формат подстановки для программы установки»."""
    text = SCRIPT_PATH.read_text(encoding="utf-8")
    if PLACEHOLDER not in text:
        raise ValueError("в sheet.gs нет заглушки __СЕКРЕТ__ — "
                         "не покажу код без секрета")
    return text.replace(PLACEHOLDER, secret)


def address_kind(url):
    """Что за адрес вставил человек.

    В работе их два, и похожи они ровно настолько, чтобы перепутать: адрес
    таблицы (docs.google.com/spreadsheets/…) нужен только чтобы открыть её
    человеку, адрес веб-приложения (script.google.com/macros/s/…/exec) — тот,
    по которому ходит бот. При первой живой настройке 2 сентября в SHEET_URL
    попал первый вместо второго, и вместо ответа пришёл 401.

    Мастер поэтому не подсказывает, а узнаёт. Подсказки «заканчивается на
    /exec» мало: она помогает тому, кто разницу уже понял, а кто не понял —
    видит длинный адрес от Google и считает, что это он и есть.

    Хвост с вопросом и якорем отрезается: Google иногда отдаёт адрес с
    параметрами, и без этого нормальный адрес не прошёл бы проверку на /exec."""
    address = (url or "").strip().split("?")[0].split("#")[0]
    if not address:
        return "пусто"
    if "docs.google.com/spreadsheets" in address:
        return "таблица"
    if "script.google.com" not in address:
        return "чужой"
    if not address.rstrip("/").endswith("/exec"):
        return "без-exec"
    return "веб-приложение"


def categories_verdict(found, expected):
    """Что сказать про прочитанный справочник статей.

    Мастер показывает не «таблица отвечает», а число. Ноль статей означает
    переименованный лист — это ловит сам мост. Пятнадцать вместо шестнадцати
    означает вторую ошибку установки: список вставили с ячейки A1, первая
    статья заняла место заголовка, и мост её законно пропустил.

    Ошибка эта дорогая не сама по себе. Не хватает всегда первой статьи —
    «Продуктов», самой ходовой; опорный тестовый чек это «Пятёрочка», и он
    уезжает в «Прочее» с предупреждением. Приёмка выглядит провалом разбора,
    хотя разбор верен.

    Расхождение в числе само по себе останавливать человека не должно:
    справочник он мог и правда сократить, это его таблица. Останавливаем
    ровно в одном случае — когда прочитанное совпадает с заготовкой без её
    первой строки. Это уже не догадка, а подпись той самой ошибки."""
    count = len(found)
    if expected and found == expected[1:]:
        return {
            "ready": False,
            "count": count,
            "note": f"Прочитано {count} статей, а в заготовке {len(expected)}. "
                    f"Не хватает первой — «{expected[0]}». Так бывает, когда "
                    "список вставили с ячейки A1: первая статья заняла место "
                    "заголовка, и мост её пропускает. Вставьте в таблице "
                    "строку выше первой, напишите в A1 слово «Статья» и "
                    "нажмите «Проверить таблицу» ещё раз.",
        }
    if count != len(expected):
        return {"ready": True, "count": count,
                "note": f"Таблица отвечает. Прочитано {count} статей — в "
                        f"заготовке было {len(expected)}. Если вы правили "
                        "список сами, так и должно быть."}
    return {"ready": True, "count": count,
            "note": f"Таблица отвечает. Прочитано {count} статей."}
