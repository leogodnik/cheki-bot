def деньги(копейки):
    return f"{копейки // 100}.{копейки % 100:02d}"


def нарисовать(данные, обрезать_итог=False):
    """Рисует чек на белом фоне и возвращает картинку."""
    позиции = данные["позиции"]
    итог = sum(ц * к for _, к, ц in позиции)
    ндс = round(итог * 20 / 120)

    высота = 300 + len(позиции) * 58 + 420
    холст = Image.new("RGB", (Ш, высота), "white")
    рис = ImageDraw.Draw(холст)
    y = 30

    def строка(текст, размер=21, жирный=False, центр=False, отступ=0):
        nonlocal y
        ф = шрифт(размер, жирный)
        if центр:
            ширина = рис.textlength(текст, font=ф)
            x = (Ш - ширина) / 2
        else:
            x = ПОЛЕ + отступ
        рис.text((x, y), текст, font=ф, fill="black")
        y += размер + 9

    def пара(слева, справа, размер=21, жирный=False):
        nonlocal y
        ф = шрифт(размер, жирный)
        рис.text((ПОЛЕ, y), слева, font=ф, fill="black")
        ширина = рис.textlength(справа, font=ф)
        рис.text((Ш - ПОЛЕ - ширина, y), справа, font=ф, fill="black")
        y += размер + 9

    def черта():
        nonlocal y
        y += 4
        рис.line([(ПОЛЕ, y), (Ш - ПОЛЕ, y)], fill="black", width=1)
        y += 12

    строка(данные["магазин"], 30, жирный=True, центр=True)
    строка(данные["юрлицо"], 19, центр=True)
    строка(данные["адрес"], 19, центр=True)
    строка(f'ИНН {данные["инн"]}', 19, центр=True)
    черта()
    строка("КАССОВЫЙ ЧЕК / ПРИХОД", 22, жирный=True, центр=True)
    черта()
    пара(f'Смена {данные["смена"]}', f'Чек {данные["чек"]}', 19)
    пара(данные["дата"], данные["время"], 19)
    строка(f'Кассир: {данные["кассир"]}', 19)
    черта()

    for название, кол, цена in позиции:
        строка(название, 20)
        пара(f"  {кол} x {деньги(цена)}", деньги(кол * цена), 20)

    черта()
    if not обрезать_итог:
        пара("ИТОГ", деньги(итог), 27, жирный=True)
        пара(данные["оплата"], деньги(итог), 21)
        пара(f'{данные["ндс_ставка"]}', деньги(ндс), 19)
        черта()
        строка(f'ФН №{данные["фн"]}', 18)
        строка(f'ФД №{данные["фд"]}  ФП {данные["фп"]}', 18)
        строка("СНО: ОСН", 18)
        строка("www.nalog.gov.ru", 18, центр=True)
        рис.rectangle([(Ш / 2 - 55, y + 10), (Ш / 2 + 55, y + 120)], outline="black", width=2)
        рис.text((Ш / 2 - 40, y + 55), "QR-код", font=шрифт(17), fill="black")
        y += 145

    return холст.crop((0, 0, Ш, min(y + 20, высота)))


def на_фоне(чек, поля=60, фон=(232, 230, 226)):
    """Кладёт чек на серый стол — так, как его снимают телефоном."""
    ш, в = чек.size
    холст = Image.new("RGB", (ш + поля * 2, в + поля * 2), фон)
    тень = Image.new("RGB", (ш + 10, в + 10), (205, 203, 199))
    холст.paste(тень, (поля + 5, поля + 5))
    холст.paste(чек, (поля, поля))
    return холст


def помять(картинка, сила=10, зерно=5):
    """Мятая бумага: волны по сетке смещений плюс неровный свет."""
    исходник = np.array(картинка).astype(np.float32)
    в, ш = исходник.shape[:2]
    ген = np.random.default_rng(7)

    мелкая = ген.normal(0, 1, (в // 26 + 2, ш // 26 + 2, 2))
    карта = np.array(
        Image.fromarray(((мелкая[:, :, 0] * 40) + 128).clip(0, 255).astype(np.uint8)).resize(
            (ш, в), Image.BICUBIC
        ),
        dtype=np.float32,
    )
    карта2 = np.array(
        Image.fromarray(((мелкая[:, :, 1] * 40) + 128).clip(0, 255).astype(np.uint8)).resize(
            (ш, в), Image.BICUBIC
        ),
        dtype=np.float32,
    )
    сдвиг_x = (карта - 128) / 128 * сила
    сдвиг_y = (карта2 - 128) / 128 * сила

    сетка_y, сетка_x = np.meshgrid(np.arange(в), np.arange(ш), indexing="ij")
    нов_x = np.clip(сетка_x + сдвиг_x, 0, ш - 1).astype(np.int32)
    нов_y = np.clip(сетка_y + сдвиг_y, 0, в - 1).astype(np.int32)
    смятая = исходник[нов_y, нов_x]

    # тени от сгибов: производная карты смещений даёт светотень
    свет = np.gradient(сдвиг_x, axis=1) + np.gradient(сдвиг_y, axis=0)
    свет = (свет / (np.abs(свет).max() + 1e-6) * 42)[:, :, None]
    смятая = смятая + свет

    смятая = смятая + ген.normal(0, зерно, смятая.shape)
    результат = Image.fromarray(смятая.clip(0, 255).astype(np.uint8))
    return результат.filter(ImageFilter.GaussianBlur(0.6))


def обрезать_снизу(картинка, доля=0.62):
    ш, в = картинка.size
    return картинка.crop((0, 0, ш, int(в * доля)))


