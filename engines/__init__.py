"""Движки. За этим швом живёт вызов конкретной модели — и только он."""

import shutil


def resolve(command):
    """Путь до программы движка или пустая строка, если её в PATH нет.

    Функция существует ради Windows, и на маке проверить её нельзя — поэтому
    объясняю подробно. npm ставит движок как `claude.cmd`, а subprocess зовёт
    CreateProcess, который к имени без расширения дописывает только `.exe` и
    про PATHEXT ничего не знает. Список `["claude", ...]` там не находит
    ничего, и мастер говорит «движок не найден» человеку, который его минуту
    назад установил, — то есть упирается в стену на первом же шаге.

    `shutil.which` про PATHEXT знает: `.CMD` стоит в его списке по умолчанию.
    На macOS и Linux он возвращает ровно тот путь, который subprocess нашёл бы
    и сам, поэтому здесь не меняется ничего.

    Пустая строка, а не None: возвращаемое значение идёт в проверку `if not`
    и в сообщение об ошибке, и два разных «ничего» в одном шве ни к чему."""
    return shutil.which(command) or ""


class EngineError(Exception):
    """Движок не ответил, ответил ошибкой или ответил не тем.

    Живёт в шве, а не в конкретном движке: agent.py ловит одно и то же
    исключение для любого движка, и codex.py не заводит своего класса и не
    импортирует чужой — иначе retry в agent.py его не поймает."""


class EngineTimeout(EngineError):
    """Движок не успел. Повторять незачем: второй заход упрётся в тот же лимит.

    Наследник EngineError, а не отдельная ветка: всё, что ловило движковый
    отказ раньше, ловит и этот. Своё имя нужно ровно одному месту — retry
    в agent.py, где таймаут единственный отказ, повторять который вредно."""
